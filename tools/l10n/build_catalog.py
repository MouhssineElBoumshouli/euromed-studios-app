"""Checks that every French text in app/lib has an English line in
tools/l10n/en.json, then writes app/lib/core/l10n/en_catalog.dart.

  python3 tools/l10n/build_catalog.py          # check + write
  python3 tools/l10n/build_catalog.py --check  # check only (CI)

New text in the app? Run it: missing texts are listed. Add them to
en.json (same text as the key = no change in English), then run again.
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', '..', 'app', 'lib', 'core', 'l10n', 'en_catalog.dart')
PH = re.compile(r'\{\d\}')


def dart(s):
    return "'" + (s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$')
                  .replace('\n', '\\n')) + "'"


def main():
    keys = json.loads(subprocess.check_output(
        [sys.executable, os.path.join(HERE, 'extract.py')]))
    en = json.load(open(os.path.join(HERE, 'en.json'), encoding='utf-8'))
    missing = [k for k in keys if k not in en]
    if missing:
        print(f'{len(missing)} text(s) without English in tools/l10n/en.json:')
        for k in missing:
            print('  ' + json.dumps(k, ensure_ascii=False) + ' — in ' + ', '.join(keys[k]))
        sys.exit(1)
    exact, patterns = {}, {}
    for k, v in sorted(en.items()):
        if k == v:
            continue
        if PH.search(k):
            # Only placeholders and punctuation: handled by splitting.
            if not re.search(r'[A-Za-zÀ-ÿ]', PH.sub('', k)):
                continue
            patterns[k] = v
        else:
            exact[k] = v
    lines = ['// GENERATED by tools/l10n/build_catalog.py from tools/l10n/en.json.',
             '// Do not edit by hand.', '',
             'const enExact = <String, String>{']
    lines += [f'  {dart(k)}: {dart(v)},' for k, v in exact.items()]
    lines += ['};', '', 'const enPatterns = <String, String>{']
    lines += [f'  {dart(k)}: {dart(v)},' for k, v in patterns.items()]
    lines += ['};', '']
    text = '\n'.join(lines)
    if '--check' in sys.argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            print('en_catalog.dart is out of date: run python3 tools/l10n/build_catalog.py')
            sys.exit(1)
        print(f'OK: {len(keys)} texts, {len(exact)} exact, {len(patterns)} with values.')
        return
    open(OUT, 'w', encoding='utf-8').write(text)
    print(f'Wrote {len(exact)} exact and {len(patterns)} patterns.')


if __name__ == '__main__':
    main()
